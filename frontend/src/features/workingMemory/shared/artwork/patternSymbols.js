const normalize = value => String(value ?? "").replace(/\uFE0F/g, "");

export const PATTERN_ARTWORK = Object.freeze(Object.fromEntries(
  Object.entries(sheets).flatMap(([sheet, entries]) => entries.map(([value, label], index) => [
    normalize(value), Object.freeze({
      value, label, sheet, src: `${ROOT}/${sheet}.webp`, row: Math.floor(index / 4), column: index % 4,
      bounds: bounds[sheet].cells[index], sheetWidth: bounds[sheet].width, sheetHeight: bounds[sheet].height,
    }),
  ])),
));

export function resolvePatternArtwork(value) {
  const token = normalize(value);
  if (PATTERN_ARTWORK[token]) return [PATTERN_ARTWORK[token]];
  // The Grade 4 composite tokens are pairs, not new question values.
  const parts = Array.from(token).map(symbol => PATTERN_ARTWORK[symbol]);
  return parts.length > 1 && parts.every(Boolean) ? parts : null;
}
