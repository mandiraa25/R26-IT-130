/*
 * Working Memory: pattern symbol map
 *
 * What is inside
 *   - PATTERN_ARTWORK: for every pattern emoji (⭐, 🍎, 🔴 ...), which artwork sheet
 *     it is on, its row/column, a readable label and its crop box.
 *   - resolvePatternArtwork(value): turns a question value into the artwork
 *     cell(s) to draw; returns null for plain text such as "A", "1" or "?".
 *
 * Why it is here
 *   Pattern questions keep their emoji values in the question data. This map is
 *   only about drawing them as illustrations, so it lives next to the component
 *   that draws them. The crop boxes come from patternSymbolBounds.json, which is
 *   generated by scripts/wm-redesign/measure-pattern-artwork.mjs.
 *
 * Where it is used
 *   - shared/artwork/PatternArtwork.jsx   resolvePatternArtwork
 *   - tests/unit/patternArtwork.test.js, workingMemoryAssets.test.js
 */
